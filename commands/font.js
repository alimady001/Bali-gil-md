async function fontCommand(sock, from, msg, q) {
    if (!q) return sock.sendMessage(from, { text: "❌ Please provide text to style!\nExample: .font Hello World" }, { quoted: msg });
    
    let response = "*STYLED TEXTS:*\n\n";
    response += `*Bold:* ${fonts.bold(q)}\n`;
    response += `*Italic:* ${fonts.italic(q)}\n`;
    response += `*Mono:* ${fonts.mono(q)}\n`;
    response += `*Bubble:* ${fonts.bubble(q)}\n`;
    response += `*Square:* ${fonts.square(q)}\n`;
    
    await sock.sendMessage(from, { text: response }, { quoted: msg });
}

